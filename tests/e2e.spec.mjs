import { test, expect } from '@playwright/test';
const BASE = process.env.BASE || 'http://localhost:8099/';
const T = process.env.TRANSPORT || 'local';
const ns = 'e2e' + Date.now();
const url = (h) => `${BASE}?transport=${T}&ns=${ns}&speed=20${h}`;
const SHOTS = '/workspace/taxi-shots/';
test.setTimeout(240000);
test('rider + real driver complete a full trip with simulated GPS', async ({ browser }) => {
  const opt = { viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, geolocation: { latitude: 40.7466, longitude: -73.8913 }, permissions: ['geolocation'] };
  const ctx = await browser.newContext(opt); // same context => BroadcastChannel works in local mode
  const dctx = T === 'mqtt' ? await browser.newContext(opt) : ctx; // separate browsers over the live broker
  const d = await dctx.newPage(), r = await ctx.newPage();
  for (const p of [d, r]) p.on('pageerror', e => console.log('PAGEERROR', e.message));
  await d.goto(url('#/driver'));
  await d.fill('input[name=name]', 'Test Driver'); await d.fill('input[name=phone]', '7185550100');
  await d.fill('input[name=car]', 'Toyota Camry'); await d.fill('input[name=plate]', 'T123456C'); await d.click('text=Continue');
  await d.check('#sim'); await d.click('#tg'); await expect(d.locator('#dst')).toContainText('Online');
  await d.screenshot({ path: SHOTS + '04-driver-online.png' });
  await r.goto(url('#/rider'));
  await r.fill('input[name=name]', 'Test Rider'); await r.fill('input[name=phone]', '7185550199'); await r.click('text=Continue');
  await r.uncheck('#demo');
  await expect(r.locator('#pu')).not.toHaveValue('', { timeout: 15000 });
  await r.fill('#de', 'Queens Center Mall');
  await r.locator('#del li[data-i]').first().click({ timeout: 15000 });
  await expect(r.locator('#fare')).toContainText('$', { timeout: 20000 });
  await r.screenshot({ path: SHOTS + '01-rider-estimate.png' });
  await r.click('#req');
  await r.screenshot({ path: SHOTS + '02-rider-searching.png' });
  await expect(d.locator('#acc')).toBeVisible({ timeout: 20000 });
  await d.screenshot({ path: SHOTS + '05-driver-offer.png' });
  await d.click('#acc');
  await expect(r.locator('#st')).toContainText('on the way', { timeout: 15000 });
  await expect(d.locator('#turn')).not.toHaveText('Starting navigation…', { timeout: 15000 });
  await d.screenshot({ path: SHOTS + '06-driver-nav-pickup.png' });
  await expect(r.locator('#eta')).toContainText('min', { timeout: 15000 });
  await r.screenshot({ path: SHOTS + '03-rider-driver-approaching.png' });
  await expect(d.locator('#turn')).toContainText('arrived', { timeout: 120000 });
  await d.click('#act'); await expect(r.locator('#st')).toContainText('arrived');
  await d.click('#start'); await expect(r.locator('#st')).toContainText('On the way to');
  await d.screenshot({ path: SHOTS + '07-driver-nav-dropoff.png' });
  await expect(d.locator('#turn')).toContainText('arrived', { timeout: 120000 });
  await d.click('#act');
  await expect(r.locator('#done')).toBeVisible({ timeout: 10000 });
  await r.locator('.stars button').nth(4).click();
  await r.screenshot({ path: SHOTS + '08-rider-receipt.png' });
  await d.screenshot({ path: SHOTS + '09-driver-complete.png' });
  await d.click('#bk'); await expect(d.locator('#etoday')).not.toHaveText('$0.00');
  await d.screenshot({ path: SHOTS + '10-driver-earnings.png' });
  const a = await ctx.newPage(); await a.goto(url('#/admin')); await a.waitForTimeout(4000);
  await a.screenshot({ path: SHOTS + '11-dispatcher.png' });
});
test('demo mode: rider completes trip with a simulated driver', async ({ browser }) => {
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, geolocation: { latitude: 40.7128, longitude: -73.8314 }, permissions: ['geolocation'] });
  const r = await ctx.newPage(); await r.goto(url('#/rider'));
  await r.fill('input[name=name]', 'Demo Rider'); await r.fill('input[name=phone]', '1'); await r.click('text=Continue');
  await expect(r.locator('#pu')).not.toHaveValue('', { timeout: 15000 });
  await r.fill('#de', 'Flushing Meadows Corona Park'); await r.locator('#del li[data-i]').first().click({ timeout: 15000 });
  await expect(r.locator('#fare')).toContainText('$', { timeout: 20000 }); await r.waitForTimeout(3500);
  await r.screenshot({ path: SHOTS + '12-demo-drivers.png' });
  await r.click('#req');
  await expect(r.locator('.demo')).toBeVisible({ timeout: 20000 });
  await expect(r.locator('#done')).toBeVisible({ timeout: 200000 });
  await r.screenshot({ path: SHOTS + '13-demo-receipt.png' });
});
